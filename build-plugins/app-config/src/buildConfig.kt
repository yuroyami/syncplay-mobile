package io.github.yuroyami.synkplay.buildplugins.appconfig

import org.jetbrains.amper.plugins.ExecutionAvoidance
import org.jetbrains.amper.plugins.Input
import org.jetbrains.amper.plugins.Output
import org.jetbrains.amper.plugins.TaskAction
import java.nio.file.Path
import java.util.Properties
import kotlin.io.path.createDirectories
import kotlin.io.path.exists
import kotlin.io.path.isRegularFile
import kotlin.io.path.readText
import kotlin.io.path.reader
import kotlin.io.path.writeText

/** `SYNKPLAY_EXO_ONLY=true` builds the exoOnly app: ExoPlayer only, no native player library. */
internal const val EXO_ONLY_ENV = "SYNKPLAY_EXO_ONLY"

/** `SYNKPLAY_DEBUG_PROTOCOL=true` makes the app log every raw protocol line. */
private const val DEBUG_PROTOCOL_ENV = "SYNKPLAY_DEBUG_PROTOCOL"

/** A local OpenSubtitles client key. local.properties can hold it as `yuroyami.keyOpenSubsApi`. */
private const val OPENSUBTITLES_ENV = "SYNKPLAY_OPENSUBTITLES_KEY"
private const val OPENSUBTITLES_PROPERTY = "yuroyami.keyOpenSubsApi"

private fun flag(name: String): Boolean = System.getenv(name)?.trim().equals("true", ignoreCase = true)

/**
 * Writes `<packageName>.KiteBuildConfig`, the object that holds the build constants.
 *
 * The task runs on every build, because IS_DEBUG and the flags come from the command line and the
 * environment. It rewrites the file only when the text changes, so an unchanged build does not
 * compile again.
 */
@TaskAction(ExecutionAvoidance.Disabled)
fun generateBuildConfig(
    appName: String,
    version: String,
    packageName: String,
    klipyApiKey: String,
    openSubtitlesKey: String,
    trinityColors: List<String>,
    // Only local.properties is read. The project is not a task output, so no task dependency is inferred.
    @Input(inferTaskDependency = false) projectDir: Path,
    @Output outputDir: Path,
) {
    buildNumber(version, 0) // validates the version
    check(trinityColors.size == 3) { "trinityColors needs three colors, found ${trinityColors.size}." }
    val local = Properties().apply {
        val file = projectDir.resolve("local.properties")
        if (file.isRegularFile()) file.reader().use(::load)
    }
    val openSubtitles = System.getenv(OPENSUBTITLES_ENV)?.takeIf { it.isNotBlank() }
        ?: local.getProperty(OPENSUBTITLES_PROPERTY)?.takeIf { it.isNotBlank() }
        ?: openSubtitlesKey

    val source = buildString {
        appendLine("// Generated by build-plugins/app-config from shared/module.yaml. Do not edit.")
        appendLine("package $packageName")
        appendLine()
        // The name is IS_DEBUG, not DEBUG. The object is public, so every field appears in the
        // Objective-C header, and Xcode defines DEBUG=1 in Debug configurations.
        appendLine("public object KiteBuildConfig {")
        appendLine("    public const val APP_NAME: String = \"${appName.kotlinEscaped()}\"")
        appendLine("    public const val APP_VERSION: String = \"${version.kotlinEscaped()}\"")
        appendLine("    public const val IS_DEBUG: Boolean = ${BuildIntent.isDebug()}")
        appendLine("    public const val DEBUG_SYNCPLAY_PROTOCOL: Boolean = ${flag(DEBUG_PROTOCOL_ENV)}")
        appendLine("    public const val EXOPLAYER_ONLY: Boolean = ${flag(EXO_ONLY_ENV)}")
        appendLine("    public const val KLIPY_API_KEY: String = \"${klipyApiKey.kotlinEscaped()}\"")
        appendLine("    public const val OPENSUBTITLES_API_KEY: String = \"${openSubtitles.kotlinEscaped()}\"")
        trinityColors.forEachIndexed { index, color ->
            appendLine("    public const val TRINITY_COLOR_${index + 1}: Long = ${argb(color)}L")
        }
        appendLine("}")
    }
    val file = outputDir.resolve(packageName.replace('.', '/')).createDirectories().resolve("KiteBuildConfig.kt")
    if (!file.exists() || file.readText() != source) file.writeText(source)
}

/** Parses `#AARRGGBB` into the Long that Compose's Color(Long) takes. */
internal fun argb(color: String): Long {
    val hex = color.removePrefix("#")
    check(hex.length == 8 && hex.all { it.isDigit() || it.lowercaseChar() in 'a'..'f' }) {
        "The color \"$color\" must have the form #AARRGGBB."
    }
    return hex.toLong(16)
}

private fun String.kotlinEscaped(): String = buildString {
    this@kotlinEscaped.forEach { c ->
        when (c) {
            '\\' -> append("\\\\")
            '"' -> append("\\\"")
            '$' -> append("\\$")
            '\n' -> append("\\n")
            else -> append(c)
        }
    }
}
